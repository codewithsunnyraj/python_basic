def test_11(a):
    """ This is my function to extract num data from list (This is docString )"""
    l =[]
    for i in a:
        if type(i) == list:
            for j in i:
                l.append(j)
        else :
            if type(i) == int or type(i) == float:
                l.append(i)
    return l

print(test_11(l))


